CREATE TABLE historic_georeference (
    unit_id TEXT PRIMARY KEY CHECK (unit_id ~ '^[0-9]{4,6}-[wh][0-9]+$'),
    document_id TEXT NOT NULL,
    document_kind TEXT NOT NULL CHECK (document_kind IN ('planimetria', 'mtn50')),
    municipality_code TEXT NOT NULL CHECK (municipality_code ~ '^[0-9]{5}$'),
    document_date DATE NOT NULL,
    document_date_precision TEXT NOT NULL CHECK (document_date_precision IN ('day', 'year')),
    scale_denominator INTEGER NOT NULL CHECK (scale_denominator > 0),
    image_kind TEXT NOT NULL CHECK (image_kind IN ('wms_render', 'original_cnig')),
    image_format TEXT NOT NULL,
    image_sha256 TEXT NOT NULL CHECK (image_sha256 ~ '^[0-9a-f]{64}$'),
    image_width_px INTEGER NOT NULL CHECK (image_width_px > 0),
    image_height_px INTEGER NOT NULL CHECK (image_height_px > 0),
    image_url TEXT NOT NULL,
    provenance_source TEXT NOT NULL,
    provenance_url TEXT NOT NULL,
    provenance_retrieved_at DATE NOT NULL,
    provenance_license TEXT NOT NULL,
    spec_image_retrieved_at DATE NOT NULL,
    control_points JSONB NOT NULL,
    control_points_sha256 TEXT NOT NULL CHECK (control_points_sha256 ~ '^[0-9a-f]{64}$'),
    a DOUBLE PRECISION NOT NULL,
    b DOUBLE PRECISION NOT NULL,
    c DOUBLE PRECISION NOT NULL,
    d DOUBLE PRECISION NOT NULL,
    e DOUBLE PRECISION NOT NULL,
    f DOUBLE PRECISION NOT NULL,
    n_retained INTEGER NOT NULL CHECK (n_retained >= 6),
    rmse_m DOUBLE PRECISION NOT NULL CHECK (rmse_m >= 0),
    max_residual_m DOUBLE PRECISION NOT NULL CHECK (max_residual_m >= 0),
    loo_rmse_m DOUBLE PRECISION NOT NULL CHECK (loo_rmse_m >= 0),
    georeferenced_by TEXT NOT NULL,
    georeferenced_at TIMESTAMPTZ NOT NULL
);
ALTER TABLE historic_trail ADD COLUMN unit_id TEXT REFERENCES historic_georeference (unit_id);
CREATE INDEX idx_historic_trail_unit ON historic_trail (unit_id);
